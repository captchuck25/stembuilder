// authored below. Block Lab units have 5 curriculum questions each, so 15
// bank-only questions bring every unit to 20.
// UNITS order is [Sequence, Loops, Nested Loops, While & If, Functions] —
// unitIdx follows that array, not the declaration order in units.ts.
// `blocksFigure` carries the QuizQ.blocks Blockly-figure DSL; the quiz-taking
// UI renders it the same way the in-lab quiz does.

