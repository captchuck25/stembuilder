const absorbed: BankQuestion[] = UNITS.flatMap((unit, unitIdx) =>
  unit.quiz.map((q, n) => {
    const meta = CURRICULUM_META[unitIdx]?.[n] ?? { topic: unit.title, difficulty: 2 as const };
    return {
      id: `block-u${unitIdx}-c${n}`,
      lab: 'block-lab' as const,
      unitIdx,
      topic: meta.topic,
      difficulty: meta.difficulty,
      question: q.question,
      ...(q.blocks ? { blocksFigure: q.blocks } : {}),
      options: q.options,
      answer: q.answer,
      explanation: q.explanation,
    };
  })
);

